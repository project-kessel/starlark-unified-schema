package docs

import (
	"fmt"
	"strings"
)

const intro = "<!-- Generated by `make docs` from docstrings in schema/*.star. Do not edit by hand. -->\n" + `
# Kessel schema DSL reference

This reference is generated from the current schema source with the command ` + "`make docs`" + ` and should not be modified directly.

It's not intended to be a language reference or how-to guide; for those, see the [Kessel docs](https://project-kessel.github.io/docs/start-here/getting-started/).

Symbols are imported from another file by filename (relative to the schema folder) and symbol name. Ex:
` + "```python" + `
load("kessel.star", "resource", "field", "uuid")
` + "```\n"

// Markdown renders the reference. Output is deterministic: no timestamps, no
// versions, LF line endings, one trailing newline.
func Markdown(ref *Reference) string {
	var b strings.Builder

	b.WriteString(intro)
	writeContents(&b, ref)

	if len(ref.Builtins) > 0 {
		fmt.Fprintf(&b, "<a id=%q></a>\n\n## Builtins\n\n", "builtins")
		b.WriteString("Predeclared by the interpreter. These need no `load()`.\n\n")
		for _, builtin := range ref.Builtins {
			writeSymbol(&b, anchor("builtin", builtin.Name), builtin.Name, builtin.Signature, FormatDoc(Dedent(builtin.Doc)))
		}
	}

	for _, module := range ref.Modules {
		fmt.Fprintf(&b, "<a id=%q></a>\n\n## `%s`\n\n", anchor("module", module.Path), module.Path)
		if module.Doc != "" {
			fmt.Fprintf(&b, "%s\n\n", module.Doc)
		}
		for _, symbol := range module.Symbols {
			writeSymbol(&b, anchor(module.Path, symbol.Name), symbol.Name, symbol.Signature, symbol.Doc)
		}
	}

	return strings.TrimRight(b.String(), "\n") + "\n"
}

func writeSymbol(b *strings.Builder, id, name, signature, doc string) {
	fmt.Fprintf(b, "<a id=%q></a>\n\n### `%s`\n\n```python\n%s\n```\n\n", id, name, signature)
	if doc == "" {
		doc = "_Undocumented._"
	}
	fmt.Fprintf(b, "%s\n\n", doc)
}

func writeContents(b *strings.Builder, ref *Reference) {
	b.WriteString("## Contents\n\n")

	if len(ref.Builtins) > 0 {
		b.WriteString("- [Builtins](#builtins)\n")
		for _, builtin := range ref.Builtins {
			fmt.Fprintf(b, "  - [`%s`](#%s)\n", builtin.Name, anchor("builtin", builtin.Name))
		}
	}

	for _, module := range ref.Modules {
		fmt.Fprintf(b, "- [`%s`](#%s)\n", module.Path, anchor("module", module.Path))
		for _, symbol := range module.Symbols {
			fmt.Fprintf(b, "  - [`%s`](#%s)\n", symbol.Name, anchor(module.Path, symbol.Name))
		}
	}

	b.WriteString("\n")
}

// anchor builds an explicit HTML id. Headings here are wrapped in backticks and
// contain slashes and dots, so deriving a link target would mean replicating
// GitHub's slug algorithm; emitting the id avoids guessing.
func anchor(scope, name string) string {
	return slug(scope) + "-" + slug(name)
}

func slug(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteByte('-')
		}
	}
	return b.String()
}
